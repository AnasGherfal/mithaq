- Node.js 24 LTS
- pnpm 11.21.0
- Next.js 16 App Router and React 19
- TypeScript strict mode
- Tailwind CSS 4 and shadcn/ui-compatible primitives
- `next-intl` with always-prefixed `/ar` and `/en` routes
- Supabase SSR clients and local Supabase CLI
- Vitest, Testing Library, Playwright, and axe
- Serwist PWA integration for Turbopack

## Prerequisites

Install:

1. Node.js 24 LTS.
2. pnpm 11 (`corepack enable` is recommended).
3. Docker Desktop or a compatible Docker runtime for local Supabase.
4. Git.

## Setup

```bash
corepack enable
pnpm install --frozen-lockfile
cp .env.example .env.local
pnpm icons:generate
```

Use only local or development values in `.env.local`. Never commit that file.

```dotenv
APP_ENV=local
NEXT_PUBLIC_SITE_URL=http://localhost:3000
NEXT_PUBLIC_SUPABASE_URL=http://127.0.0.1:54321
NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=<local publishable key from Supabase status>
```

Start local Supabase and read its local publishable key:

```bash
pnpm db:start
pnpm exec supabase status
```

Run the application:

```bash
pnpm dev
```

Open `http://localhost:3000`. The root URL deterministically redirects to
`/ar`; English is available at `/en`.

## Verification commands

```bash
pnpm icons:generate
pnpm format:check
pnpm lint
pnpm typecheck
pnpm test
pnpm build
pnpm test:db
pnpm exec playwright install --with-deps chromium
pnpm test:e2e
```

`pnpm check` runs formatting, linting, type checking, unit tests, and a
production build in that order. Run `pnpm build` before `pnpm test:e2e`, because
the E2E suite starts the production server.

Stop local Supabase when finished:

```bash
pnpm db:stop
```

## PWA privacy boundary

The service worker precaches only build assets and the bilingual offline
fallback. It defines no runtime cache for APIs or Supabase requests and must
never cache authenticated responses, private questionnaire data, profile
information, or protected media. This cache policy must be reviewed again
before authenticated routes are introduced.

The mark in `public/icons` is an original, provisional architectural-threshold
symbol generated by `scripts/generate-pwa-icons.mjs`. It is not a final brand
identity.

