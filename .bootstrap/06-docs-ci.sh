# Mithaq | ميثاق

**تعارف موثّق للزواج الجاد**

This repository contains the production-oriented technical foundation for
Mithaq, an Arabic-first, private marriage-introduction network for serious
adult Libyans in Libya and the diaspora.

## Current milestone

**Milestone 1 — Project Foundation**

This release establishes the framework, design tokens, Arabic/English routing,
RTL/LTR behavior, Supabase client boundaries, automated testing, CI, and a
privacy-conservative PWA shell. It does **not** include registration, phone OTP,
